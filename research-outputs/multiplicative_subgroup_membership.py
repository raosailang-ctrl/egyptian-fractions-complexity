#!/usr/bin/env python3
"""Exact membership test for -1 in H=<prime factors of D> mod M.

For each p^(2a)||M, (Z/p^(2a)Z)^* is cyclic. Choose a primitive root,
write each ell_i and -D as discrete logarithms, then test whether the target
vector lies in the integer column lattice generated by the generator-log
matrix and the cyclic-order relation columns. Membership is certified by
equality of gcds of maximal minors before and after adjoining the target.
Requires SymPy.
"""
from __future__ import annotations
from itertools import combinations
from math import gcd
import argparse
import sympy as sp
from sympy import factorint, primitive_root, discrete_log

DEFAULT_T=(3,7,17,69,137,185)

def family(t):
    L=[1+3*t,1+14*t,1+60*t,1+36*t,4*t-1,1+84*t,1+15*t,1+18*t]
    D=int(sp.prod(L)); h=t*(12*t+1)
    exponents={}
    for x in L:
        for p,a in factorint(x).items():
            exponents[int(p)]=exponents.get(int(p),0)+int(a)
    return D,h,sorted(exponents)

def gcd_of_maximal_minors(A):
    rows=len(A); cols=len(A[0])
    value=0; count=0
    for selected in combinations(range(cols),rows):
        det=int(sp.Matrix([[A[i][j] for j in selected] for i in range(rows)]).det())
        value=gcd(value,abs(det)); count+=1
    return value,count

def analyze(t):
    D,h,ells=family(t); M=h*h
    components=[]
    for p,a in sorted(factorint(h).items()):
        modulus=int(p)**(2*int(a))
        order=int(sp.totient(modulus))
        generator=int(primitive_root(modulus))
        logs=[int(discrete_log(modulus,ell%modulus,generator)) for ell in ells]
        target=int(discrete_log(modulus,(-D)%modulus,generator))
        components.append(dict(p=int(p),a=int(a),modulus=modulus,
          order=order,generator=generator,logs=logs,target=target))
    rows=[]
    for j,c in enumerate(components):
        rows.append(c["logs"]+[-c["order"] if j==i else 0
                               for i in range(len(components))])
    target=[c["target"] for c in components]
    before,n_before=gcd_of_maximal_minors(rows)
    after,n_after=gcd_of_maximal_minors([row+[target[i]] for i,row in enumerate(rows)])
    return dict(t=t,D=D,h=h,M=M,ells=ells,components=components,
      lattice_index_gcd=before,augmented_index_gcd=after,
      minors_before=n_before,minors_after=n_after,
      minus_one_in_H=(before==after))

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--values",nargs="*",type=int,default=DEFAULT_T)
    args=ap.parse_args()
    for t in args.values:
        x=analyze(t)
        print(f"t={t}: M={x['M']} ell_count={len(x['ells'])}")
        print("  ell primes:",x["ells"])
        print("  cyclic components (p, modulus, order, primitive root, target log):",
          [(c["p"],c["modulus"],c["order"],c["generator"],c["target"])
           for c in x["components"]])
        print("  gcd maximal minors:",x["lattice_index_gcd"],
              "augmented:",x["augmented_index_gcd"])
        print("  determinant minors checked:",x["minors_before"],x["minors_after"])
        print("  -1 in H:",x["minus_one_in_H"])
    print("MULTIPLICATIVE_SUBGROUP_MEMBERSHIP_CHECKS: PASS")

if __name__=="__main__":main()
